// ЛАБОРАТОРНА РОБОТА 3.2. Чисельне розв'язання нелінійного рівняння.
// Мета: знайти наближене значення x, для якого f(x) = 0, із заданою
// абсолютною похибкою eps на введеному відрізку [a; b].
//
// Структура програми:
//   f(), d1(), d2() — допоміжні функції для обчислення f, f' та f'';
//   solve(method)  — введення даних, перевірки та реалізація двох методів;
//   main()         — точка входу, головне меню і повторний вибір дії.
// Чисельний метод — алгоритм пошуку кореня. Тут обидва алгоритми
// реалізовані гілками всередині solve(), а не окремими функціями.
//
// Позначення в коментарях: root — справжній корінь, x — його наближення,
// f'(x) — перша похідна, f''(x) — друга похідна, |...| — модуль числа.
// Коментарі пояснюють алгоритм; вони не виконуються під час роботи програми.

// Стандартне введення/виведення: printf() друкує, scanf() читає дані.
#include <stdio.h>
// Математичні засоби: pow() — степінь, fabs() — модуль, isfinite() — скінченність.
#include <math.h>
// Засоби відліку часу: clock(), тип clock_t та константа CLOCKS_PER_SEC.
#include <time.h>

// Функція варіанта 10: шукаємо корені рівняння f(x) = 0.
// Вхід: дійсний аргумент x. Результат: значення полінома f(x).
// double — тип дійсних чисел подвійної точності; return повертає результат.
// pow(x - 25, 2) обчислює квадрат, pow(x + 25, 3) — куб відповідного виразу.
// Функція неперервна на всій числовій осі, тому можна застосовувати
// ознаку існування кореня за різними знаками на кінцях відрізка.
double f(double x)
{
    return 0.25 * pow(x - 25, 2) + pow(x + 25, 3) / 100 + 1;
}

// Перша похідна потрібна для перевірки єдиності кореня.
// Аналітична похідна f'(x) = 0.5*(x - 25) + 0.03*(x + 25)^2.
// Її знак визначає зростання або спадання f, а мінімальний модуль
// використовується для оцінювання похибки в методі хорд.
double d1(double x)
{
    return 0.5 * (x - 25) + 3 * pow(x + 25, 2) / 100;
}

// Друга похідна допомагає обрати нерухому точку хорди.
// Аналітична друга похідна f''(x) = 0.06*x + 2.
// Її сталий ненульовий знак на відрізку підтверджує сталу опуклість f;
// разом зі знаком f на межах це дозволяє вибрати нерухомий кінець хорди.
double d2(double x)
{
    return 0.5 + 6 * (x + 25) / 100;
}

// method = 1: половинне ділення; method = 2: метод хорд.
// Спільна процедура розв'язання; void означає відсутність значення результату.
// Параметр method надходить із main(): 1 — половинне ділення, 2 — хорди.
// Дані та результат виводяться в консоль. Локальні змінні створюються
// заново під час кожного виклику, тому різні запуски не змішують свій стан.
// return без значення завершує тільки solve() і повертає керування в main().
void solve(int method)
{
    // Межі ізоляції, точність, значення функції та похідної.
    // a, b — ліва та права межі; eps — допустима абсолютна похибка кореня.
    // fa = f(a), fb = f(b); da = f'(a), db = f'(b) — збережені значення.
    // f'(x) = 0.03*x^2 + 2*x + 6.25 — парабола з гілками вгору.
    // vertex = -2/(2*0.03) = -100/3 — координата її мінімуму.
    // Цей розрахунок вершини стосується саме математичної функції варіанта 10.
    double a, b, eps, fa, fb, da, db, vertex = -100.0 / 3.0;
    // lower, upper — мінімальне та максимальне значення f' на [a; b].
    // t — тимчасове значення f' у вершині; x — поточне наближення; fx = f(x).
    // fixed, fixed_f — нерухомий кінець хорди та значення f у цій точці.
    // Початкові нулі fixed і fixed_f замінюються після вибору кінця хорди.
    double lower, upper, t, x, fx, fixed = 0, fixed_f = 0;
    // old — попереднє наближення для виявлення зупинки чисельного прогресу.
    // min_d — додатна нижня межа |f'|; seconds — накопичений час обчислень.
    double old, min_d = 0, seconds = 0;
    // denominator — знаменник формули хорди; next_x і next_fx — кандидат
    // на нове наближення та f(next_x). Спочатку перевіряємо їх коректність,
    // а вже потім замінюємо збережені x та fx.
    double denominator, next_x, next_fx;
    // clock_t зберігає відлік таймера; секунди отримуємо після перетворення.
    clock_t start;

    // Ліміт, загальна кількість ітерацій та кількість у поточній групі.
    // int зберігає цілі числа. limit — розмір однієї дозволеної групи кроків.
    // iterations рахує всі виконані кроки; batch — кроки після останнього
    // дозволу продовжити групу. debug керує лише друком проміжних результатів.
    int limit, debug, iterations = 0, batch = 0;

    // Ознаки завершення і режиму обчислень.
    // Логічні прапорці подано цілими числами: 0 — ні, 1 — так.
    // unlimited — вимкнено ліміт груп; found — виконано критерій точності;
    // stopped — користувач обрав зупинку; stalled — уточнення неможливе
    // через округлення або небезпечний чисельний крок. action — пункт меню.
    int unlimited = 0, found = 0, stopped = 0, stalled = 0, action;

    // Введення початкових умов і перевірка допустимості даних.
    printf("Input a and b: ");
    // %lf у scanf читає double; &a та &b передають адреси змінних для запису.
    // Повернене число 2 означає успішне читання обох значень.
    // || — логічне АБО: достатньо однієї помилки, щоб відхилити дані.
    // isfinite() відкидає NaN і нескінченність; a < b задає непорожній відрізок.
    if (scanf("%lf%lf", &a, &b) != 2 || !isfinite(a) || !isfinite(b) || a >= b)
    {
        printf("Incorrect interval.\n");
        return;
    }

    printf("Input epsilon (> 0): ");
    // eps повинно бути скінченним додатним числом, наприклад 0.000001.
    // Це допустима похибка аргументу x, а не кількість знаків після коми.
    if (scanf("%lf", &eps) != 1 || !isfinite(eps) || eps <= 0)
    {
        printf("Incorrect epsilon.\n");
        return;
    }

    printf("Maximum iterations: ");
    // %d читає int. Додатний limit задає момент появи меню продовження,
    // а не обов'язкову кількість кроків: точність може бути досягнута раніше.
    if (scanf("%d", &limit) != 1 || limit <= 0)
    {
        printf("Incorrect number of iterations.\n");
        return;
    }

    // Режим налагодження: 1 — друкувати кожну ітерацію, 0 — не друкувати.
    printf("Show each iteration? (1 - Yes, 0 - No): ");
    // && — логічне І. Якщо debug не дорівнює ані 0, ані 1, вибір некоректний.
    // Режим налагодження тут означає друк кроків алгоритму в консоль.
    if (scanf("%d", &debug) != 1 || (debug != 0 && debug != 1))
    {
        printf("Incorrect debug mode.\n");
        return;
    }

    // Фіксуємо час перед початковими обчисленнями. Цей відлік використано
    // для випадку кореня на межі; перед основним циклом його запускаємо заново.
    start = clock();
    fa = f(a);
    fb = f(b);

    // Скінченні аргументи також можуть спричинити переповнення f(x).
    // Навіть скінченне введене x може дати нескінченність через переповнення
    // степеня. З такими значеннями порівняння знаків і формули ненадійні.
    if (!isfinite(fa) || !isfinite(fb))
    {
        printf("Function values are not finite. Choose another interval.\n");
        return;
    }

    // Точний корінь на межі повертаємо до перевірки похідної:
    // його значення вже відоме, навіть якщо єдиність не підтверджено.
    // Перевіряємо саме обчислений нуль double: окремий випадок, коли
    // шукати наближення ітераціями вже не потрібно. Єдиність тут не заявляємо.
    if (fa == 0 || fb == 0)
    {
        if (fa == 0) x = a;
        else x = b;

        // %.10lf друкує дійсне число з 10 знаками після коми, \n — новий рядок.
        // Формат виведення не встановлює точність самого чисельного методу.
        printf("Root = %.10lf\n", x);
        printf("f(root) = 0\nIterations = 0\n");
        printf("CPU time = %.9lf seconds\n",
               (double)(clock() - start) / CLOCKS_PER_SEC);
        printf("Required accuracy achieved.\n");
        return;
    }

    // Для неперервної функції різні знаки на кінцях гарантують корінь.
    // Однакові знаки не доводять відсутність коренів у довільної функції,
    // але не дають потрібної цим реалізаціям гарантії ізоляції кореня.
    // Після відхилення нульових меж різні знаки гарантують хоча б один корінь.
    if ((fa > 0 && fb > 0) || (fa < 0 && fb < 0))
    {
        printf("No sign change on the interval.\n");
        return;
    }

    // Перевіряємо сталий знак першої похідної на всьому проміжку.
    // Для варіанта 10 d1(x) — парабола з вершиною у точці -100/3.
    da = d1(a);
    db = d1(b);
    // Починаємо пошук діапазону похідної зі значення на лівій межі.
    lower = da;
    upper = da;
    // Уточнюємо мінімум і максимум за значенням похідної на правій межі.
    if (db < lower) lower = db;
    if (db > upper) upper = db;

    // Для квадратичної похідної її внутрішній екстремум можливий тільки
    // у вершині. Перевірка кінців і вершини охоплює весь відрізок,
    // на відміну від перевірки похідної лише в декількох довільних точках.
    if (a < vertex && vertex < b)
    {
        t = d1(vertex);
        if (t < lower) lower = t;
        if (t > upper) upper = t;
    }

    printf("\nf(a) = %.6lf, f(b) = %.6lf\n", fa, fb);
    printf("Range of f'(x): [%.6lf; %.6lf]\n", lower, upper);

    // Сталий ненульовий знак похідної дає строгу монотонність;
    // разом зі зміною знака f(x) це гарантує рівно один корінь.
    // lower > 0: f' додатна всюди, отже f строго зростає.
    // upper < 0: f' від'ємна всюди, отже f строго спадає.
    // ! заперечує умову: якщо жодної гарантії немає, просимо інший відрізок.
    // Відмова означає недостатність цієї перевірки, а не доказ кількох коренів.
    if (!(lower > 0 || upper < 0))
    {
        printf("Uniqueness of the root is not confirmed.\n");
        return;
    }
    printf("Exactly one root on the interval.\n");

    // Початкове наближення та узгоджене з ним значення функції.
    // У методі половинного ділення їх замінить середина першого відрізка;
    // у методі хорд вони задають початковий рухомий кінець.
    x = a;
    fx = fa;

    // Підготовка, потрібна лише методу хорд. Для половинного ділення
    // стала опуклість не потрібна, тому цю перевірку він пропускає.
    if (method == 2)
    {
        // Метод хорд потребує сталого ненульового знака другої похідної.
        // f'' цього варіанта лінійна. Однакові ненульові знаки на її кінцях
        // гарантують такий самий знак на всьому відрізку [a; b].
        if (!((d2(a) > 0 && d2(b) > 0) ||
              (d2(a) < 0 && d2(b) < 0)))
        {
            printf("Choose an interval with constant sign of f''(x).\n");
            return;
        }

        // Кінець, де f(x) і f''(x) мають однакові знаки, є нерухомим.
        // Це перевірка f(a)*f''(a) > 0 через порівняння знаків без множення.
        // Якщо підходить a, фіксуємо a та рухаємо x від b. Інакше фіксуємо b;
        // рухомим залишається вже заданий x = a. Нерухома точка не змінюється.
        if ((fa > 0 && d2(a) > 0) || (fa < 0 && d2(a) < 0))
        {
            fixed = a;
            fixed_f = fa;
            x = b;
            fx = fb;
        }
        else
        {
            fixed = b;
            fixed_f = fb;
        }

        // Мінімальний модуль похідної потрібен для оцінки похибки.
        // Після перевірки сталого знака f' її модуль має додатний мінімум.
        // Перевіряємо обидва кінці та вершину, якщо вона лежить усередині.
        // fabs() повертає модуль дійсного числа, тому min_d не залежить від знака f'.
        min_d = fabs(da);
        if (fabs(db) < min_d) min_d = fabs(db);
        if (a < vertex && vertex < b && fabs(d1(vertex)) < min_d)
            min_d = fabs(d1(vertex));

        // Ділення на min_d допустиме лише для додатної скінченної оцінки.
        if (!isfinite(min_d) || min_d <= 0)
        {
            printf("Cannot estimate root accuracy.\n");
            return;
        }
    }

    // Накопичуємо час ділянок обчислення; очікування вибору не враховуємо.
    start = clock();

    // Повторюємо кроки, поки всі три ознаки завершення дорівнюють нулю.
    // Продовження без ліміту також підпорядковується цим перевіркам:
    // воно не скасовує ані точність, ані захист від чисельної зупинки.
    while (!found && !stopped && !stalled)
    {
        // Після вичерпання ліміту надаємо три дії за умовою завдання.
        // Меню з'являється перед наступною ітерацією після виконання limit кроків.
        // У режимі unlimited ця умова хибна і меню більше не перериває пошук.
        if (!unlimited && batch >= limit)
        {
            // Додаємо завершену ділянку часу до накопиченої суми.
            // (double) забезпечує дійсне ділення; CLOCKS_PER_SEC переводить
            // відліки таймера в секунди. Читання відповіді починається вже після цього.
            seconds += (double)(clock() - start) / CLOCKS_PER_SEC;
            printf("\nIteration limit reached (%d total).\n", iterations);

            // do...while виконує запит хоча б один раз і повторює його,
            // доки введене ціле число не належить діапазону 1...3.
            do
            {
                printf("1 - Continue %d iterations\n", limit);
                printf("2 - Continue without limit\n");
                printf("3 - Stop and show result\n");
                printf("Choose: ");

                // Якщо число не прочитано, зокрема через EOF, обираємо зупинку.
                // break виходить із найближчого циклу do...while.
                if (scanf("%d", &action) != 1)
                {
                    action = 3;
                    break;
                }
            } while (action < 1 || action > 3);

            // Новий відлік починається після введення відповіді, тому очікування
            // користувача не додається до часу жодної обчислювальної ділянки.
            start = clock();

            if (action == 3)
            {
                // Установлюємо причину завершення; наступний break залишає цикл пошуку.
                stopped = 1;
                break;
            }

            // Продовження на нову групу або без обмеження кількості.
            // Скидаємо тільки лічильник групи; загальний iterations, поточне x
            // та звужені межі зберігаємо. Обчислення не починаються спочатку.
            // Для action == 2 встановлюємо unlimited; розмір limit не змінюємо.
            if (action == 1) batch = 0;
            else unlimited = 1;
        }

        if (method == 1)
        {
            // Половинне ділення: беремо середину поточного проміжку.
            // МЕТОД ПОЛОВИННОГО ДІЛЕННЯ: нове x — середина поточного відрізка.
            // Після аналізу знака f(x) лишаємо половину, яка містить корінь.
            x = a + (b - a) / 2;
            fx = f(x);
        }
        else
        {
            // Метод хорд: перетин хорди з віссю X дає нове наближення.
            // МЕТОД ХОРД ІЗ НЕРУХОМИМ КІНЦЕМ: проводимо пряму через точки
            // (fixed, fixed_f) та (x, fx); її перетин з віссю X дає next_x.
            // Різниця значень функції є знаменником формули цього перетину.
            denominator = fixed_f - fx;
            // Нульовий або нескінченний знаменник не дозволяє безпечно
            // виконати наступний крок. Зберігаємо останній коректний результат.
            if (denominator == 0 || !isfinite(denominator))
            {
                stalled = 1;
                break;
            }

            // Перевіряємо нову точку до заміни останнього коректного наближення.
            // Формула хорди: x_new = x - f(x)*(fixed - x)/(f(fixed) - f(x)).
            // За виконаних умов збіжності точка повинна лишатися на [a; b].
            next_x = x - fx * (fixed - x) / denominator;
            // Відхиляємо переповнення, NaN або вихід нового наближення за відрізок.
            if (!isfinite(next_x) || next_x < a || next_x > b)
            {
                stalled = 1;
                break;
            }
            // Перевіряємо також саме значення f у новій точці до оновлення стану.
            next_fx = f(next_x);
            if (!isfinite(next_fx))
            {
                stalled = 1;
                break;
            }

            // Запам'ятовуємо попередню точку для перевірки округлення,
            // потім одночасно оновлюємо наближення і відповідне йому f(x).
            old = x;
            x = next_x;
            fx = next_fx;
        }

        // ++ збільшує значення на одиницю. Рахуємо тільки виконаний крок;
        // невдала спроба, завершена через break вище, сюди не доходить.
        iterations++;
        batch++;

        // Проміжний друк показує номер кроку, поточне наближення та нев'язку f(x).
        // Нев'язка — наскільки обчислене значення функції відрізняється від нуля.
        if (debug == 1)
            printf("%d: x = %.10lf, f(x) = %.10lf\n", iterations, x, fx);

        if (method == 1)
        {
            // Похибка середньої точки не більша за половину довжини.
            // Для середини відрізка, що містить root: |x - root| <= (b - a)/2.
            // Умова виконується при обчисленому f(x) == 0 або достатній вузькості.
            if (fx == 0 || (b - a) / 2 <= eps)
                found = 1;
            // Через скінченну точність double середина може округлитися до межі.
            // Якщо точність ще не досягнуто, подальше ділення вже не уточнює x.
            else if (x == a || x == b)
                stalled = 1;
            // Різні знаки f(a) і f(x): корінь залишається в лівій половині [a; x].
            // Інакше зберігаємо праву половину [x; b]. Разом із межею
            // оновлюємо відповідне значення функції, щоб не обчислювати його знову.
            else if ((fa < 0 && fx > 0) || (fa > 0 && fx < 0))
            {
                b = x;
                fb = fx;
            }
            else
            {
                a = x;
                fa = fx;
            }
        }
        else
        {
            // За теоремою Лагранжа |x - root| <= |f(x)| / min_d.
            // Мала зміна x сама по собі ще не гарантує потрібної точності.
            // min_d <= |f'(u)| для кожної u на [a; b], тому ця оцінка
            // контролює похибку аргументу x. Сам лише малий f(x) без урахування
            // масштабу похідної не давав би такої гарантії.
            if (fx == 0 || fabs(fx) / min_d <= eps)
                found = 1;
            // Новий крок округлився до попереднього x, а умова точності не виконана.
            // Фіксуємо чисельну зупинку, щоб не повторювати те саме наближення без кінця.
            else if (x == old)
                stalled = 1;
        }
    }

    // Після виходу з циклу додаємо останню ділянку часу, яку ще не накопичували.
    // Роздільність таймера обмежена: короткі обчислення можуть дати 0 секунд.
    seconds += (double)(clock() - start) / CLOCKS_PER_SEC;

    // Спільний результат для обох методів.
    // Фінальні дані: останнє наближення, нев'язка, загальна кількість кроків
    // і виміряний час. Навіть при достроковій зупинці показуємо наявне наближення.
    printf("\nRoot approximation = %.10lf\n", x);
    printf("f(root) = %.10lf\n", fx);
    printf("Iterations = %d\nCPU time = %.9lf seconds\n",
           iterations, seconds);

    // Статус пояснює, як трактувати результат: потрібна точність підтверджена,
    // подальший чисельний крок неможливий або пошук завершено вибором користувача.
    if (found)
        printf("Required accuracy achieved.\n");
    else if (stalled)
        printf("Stopped: no numerical progress.\n");
    else
        printf("Stopped by user before required accuracy.\n");
}

// Головне меню викликає спільну функцію з потрібним методом.
// Виконання C-програми починається з main(). void у дужках означає відсутність
// параметрів функції, int — цілий код завершення, який вона повертає системі.
int main(void)
{
    // choice — пункт головного меню: 1, 2 або 0 для завершення програми.
    int choice;

    // Нескінченний цикл меню: після повернення із solve() можна провести
    // новий розрахунок. Вихід здійснюється операторами return 0 нижче.
    for (;;)
    {
        printf("\n1 - Bisection method\n");
        printf("2 - Chord method\n");
        printf("0 - Exit\nChoose: ");

        // Якщо замість номера отримано текст або кінець вводу, завершуємо main().
        // scanf не вилучає непрочитані літери: після помилки всередині solve()
        // вони можуть спричинити завершення програми на цій перевірці.
        if (scanf("%d", &choice) != 1)
            return 0;

        // return 0 із main() завершує всю програму з кодом успіху.
        if (choice == 0)
            return 0;

        // До solve() передаємо тільки підтримуваний номер методу.
        // Інше ціле число викликає повідомлення про помилку та новий показ меню.
        if (choice == 1 || choice == 2)
            solve(choice);
        else
            printf("Incorrect option.\n");
    }
}
